// Copies contract ABIs from Foundry's out/ and every deployments/<chainId>.json into the web app,
// so the frontend never hard-codes an address or an ABI.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const deploymentsDir = join(root, "contracts", "deployments");
const target = join(root, "app", "src", "generated");
mkdirSync(target, { recursive: true });

const contracts = [
  "PassIssuer",
  "ShiftGate",
  "IncidentSwitch",
  "PermissionedRegistry",
  "PermissionedResolver",
  "MockUSDC",
];

let abis = "// Generated by scripts/export-abis.mjs. Do not edit.\n\n";
for (const name of contracts) {
  const file = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing ${file}. Run "forge build" in contracts/ first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  abis += `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(target, "abis.ts"), abis);

const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const f of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, f), "utf8"));
    deployments[String(d.chainId)] = d;
  }
}
writeFileSync(join(target, "deployments.json"), JSON.stringify(deployments, null, 2) + "\n");
console.log(`Exported ${contracts.length} ABIs and ${Object.keys(deployments).length} deployment(s) to app/src/generated`);
